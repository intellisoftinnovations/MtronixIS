@register.simple_tag
def icon(name, size=20, cls=""):
    body = ICONS.get(name, ICONS["box"])
    return mark_safe(
        f'<svg class="icon {cls}" width="{int(size)}" height="{int(size)}" viewBox="0 0 24 24" fill="none" '
        f'stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{body}</svg>'
    )


@register.filter
def bdtime(value):
    """Bangladesh time with zone suffix."""
    return format_bd(value, with_tz=True)


@register.filter
def bdtime_short(value):
    return format_bd(value, with_tz=False)


@register.simple_tag(takes_context=True)
def url_replace(context, **kwargs):
    """Rebuild the current querystring overriding the given params."""
    params = context["request"].GET.copy()
    for k, v in kwargs.items():
        if v in (None, ""):
            params.pop(k, None)
        else:
            params[k] = v
    encoded = params.urlencode()
    return f"?{encoded}" if encoded else "?"


@register.simple_tag(takes_context=True)
def nav_active(context, *prefixes):
    path = context["request"].path
    for p in prefixes:
        if p == "/" and path == "/":
            return "active"
        if p != "/" and path.startswith(p):
            return "active"
    return ""


@register.filter
def status_badge(status):
    return {"active": "success", "hold": "warning", "damaged": "danger", "closed": "muted"}.get(status, "muted")


@register.filter
def get_item(d, key):
    try:
        return d.get(key)
    except AttributeError:
        return None


